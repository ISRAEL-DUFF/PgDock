// Package typegen writes typed definitions of a project's tables, views and
// functions for the SDKs (V4 §3.7): TypeScript, Dart and Go, from the data
// API's catalog. Each table gets a row type, and tables an insert and an
// update type, whose optional fields are the columns with a default or
// that may be null.
package typegen

import (
	"fmt"
	"sort"
	"strings"
	"unicode"

	"github.com/israel-duff/pgdock/internal/datacat"
)

// Languages.
const (
	TS   = "ts"
	Dart = "dart"
	Go   = "go"
)

// Options for Generate.
type Options struct {
	Ref     string // the project reference, for the header
	Package string // Go's package name (default "pgdtypes")
}

// Generate renders cat in lang.
func Generate(cat *datacat.Catalog, lang string, o Options) (string, error) {
	switch lang {
	case TS:
		return genTS(cat, o), nil
	case Dart:
		return genDart(cat, o), nil
	case Go:
		return genGo(cat, o), nil
	}
	return "", fmt.Errorf("unknown language %q: ts, dart or go", lang)
}

func header(comment, ref string) string {
	return fmt.Sprintf("%s Generated by pgdock gen types for project %s. Do not edit: run it again after changing the schema.\n", comment, ref)
}

// relations groups a catalog's relations by schema, in order.
func relations(cat *datacat.Catalog) (schemas []string, bySchema map[string][]*datacat.Table) {
	bySchema = map[string][]*datacat.Table{}
	for _, t := range cat.Tables() {
		bySchema[t.Schema] = append(bySchema[t.Schema], t)
	}
	for _, s := range cat.Schemas {
		if len(bySchema[s]) > 0 || len(functionsIn(cat, s)) > 0 {
			schemas = append(schemas, s)
		}
	}
	return schemas, bySchema
}

func functionsIn(cat *datacat.Catalog, schema string) []*datacat.Function {
	var out []*datacat.Function
	var keys []string
	for k := range cat.Functions {
		if strings.HasPrefix(k, schema+".") {
			keys = append(keys, k)
		}
	}
	sort.Strings(keys)
	for _, k := range keys {
		out = append(out, cat.Functions[k]...)
	}
	return out
}

func writable(t *datacat.Table) bool {
	return t.Kind == datacat.KindTable || t.Kind == datacat.KindPart
}

// optional reports whether an insert may leave c out.
func optional(c *datacat.Column) bool { return c.Nullable || c.HasDefault }

// camel turns snake_case into CamelCase (upper) or camelCase.
func camel(s string, upper bool) string {
	var b strings.Builder
	up := upper
	for i, r := range s {
		switch {
		case r == '_' || r == '-' || r == ' ' || r == '.':
			up = true
		case up:
			b.WriteRune(unicode.ToUpper(r))
			up = false
		case i == 0 && !upper:
			b.WriteRune(unicode.ToLower(r))
		default:
			b.WriteRune(r)
		}
	}
	out := b.String()
	if out == "" || !unicode.IsLetter([]rune(out)[0]) {
		out = "X" + out
	}
	return out
}

// goName also upper-cases common initialisms (ID, URL).
func goName(s string) string {
	n := camel(s, true)
	for _, w := range []string{"Id", "Url", "Uuid", "Api", "Json", "Http", "Ip"} {
		if strings.HasSuffix(n, w) {
			n = strings.TrimSuffix(n, w) + strings.ToUpper(w)
		}
	}
	return n
}

// ---- TypeScript -------------------------------------------------------------

func tsType(c *datacat.Column) string {
	var t string
	elem := strings.TrimPrefix(c.TypName, "_")
	switch {
	case len(c.Enum) > 0:
		var labels []string
		for _, l := range c.Enum {
			labels = append(labels, fmt.Sprintf("%q", l))
		}
		t = strings.Join(labels, " | ")
	case c.Category == 'A':
		t = tsScalar(elem) + "[]"
	default:
		t = tsScalar(c.TypName)
	}
	if c.Nullable {
		t += " | null"
	}
	return t
}

func tsScalar(typname string) string {
	switch typname {
	case "int2", "int4", "int8", "float4", "float8", "numeric", "oid", "money":
		return "number"
	case "bool":
		return "boolean"
	case "json", "jsonb":
		return "Json"
	}
	return "string"
}

func tsKey(name string) string {
	for i, r := range name {
		if !unicode.IsLetter(r) && r != '_' && r != '$' && (i == 0 || !unicode.IsDigit(r)) {
			return fmt.Sprintf("%q", name)
		}
	}
	return name
}

func genTS(cat *datacat.Catalog, o Options) string {
	var b strings.Builder
	b.WriteString(header("//", o.Ref))
	b.WriteString("\nexport type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\n\n")
	b.WriteString("export interface Database {\n")
	schemas, by := relations(cat)
	for _, s := range schemas {
		fmt.Fprintf(&b, "  %s: {\n    Tables: {\n", tsKey(s))
		for _, t := range by[s] {
			if !writable(t) {
				continue
			}
			fmt.Fprintf(&b, "      %s: {\n        Row: {\n", tsKey(t.Name))
			for _, c := range t.Columns {
				fmt.Fprintf(&b, "          %s: %s;\n", tsKey(c.Name), tsType(c))
			}
			b.WriteString("        };\n        Insert: {\n")
			for _, c := range t.Columns {
				if c.Generated {
					continue
				}
				q := ""
				if optional(c) {
					q = "?"
				}
				fmt.Fprintf(&b, "          %s%s: %s;\n", tsKey(c.Name), q, tsType(c))
			}
			b.WriteString("        };\n        Update: {\n")
			for _, c := range t.Columns {
				if c.Generated {
					continue
				}
				fmt.Fprintf(&b, "          %s?: %s;\n", tsKey(c.Name), tsType(c))
			}
			b.WriteString("        };\n      };\n")
		}
		b.WriteString("    };\n    Views: {\n")
		for _, t := range by[s] {
			if writable(t) {
				continue
			}
			fmt.Fprintf(&b, "      %s: {\n        Row: {\n", tsKey(t.Name))
			for _, c := range t.Columns {
				fmt.Fprintf(&b, "          %s: %s;\n", tsKey(c.Name), tsType(c))
			}
			b.WriteString("        };\n      };\n")
		}
		b.WriteString("    };\n    Functions: {\n")
		seen := map[string]bool{}
		for _, f := range functionsIn(cat, s) {
			if seen[f.Name] {
				continue // overloads: the first
			}
			seen[f.Name] = true
			fmt.Fprintf(&b, "      %s: {\n        Args: {", tsKey(f.Name))
			for _, a := range f.Args {
				if a.Name == "" {
					continue
				}
				q := ""
				if a.HasDefault {
					q = "?"
				}
				c := &datacat.Column{TypName: a.TypName, Category: a.Category}
				fmt.Fprintf(&b, " %s%s: %s;", tsKey(a.Name), q, tsType(c))
			}
			b.WriteString(" };\n        Returns: ")
			switch {
			case f.Columns != nil:
				b.WriteString("{")
				for _, c := range f.Columns {
					fmt.Fprintf(&b, " %s: %s;", tsKey(c.Name), tsType(c))
				}
				b.WriteString(" }")
				if f.RetSet {
					b.WriteString("[]")
				}
			default:
				b.WriteString(tsType(&datacat.Column{TypName: f.RetTypName, Category: f.RetCategory, Nullable: true}))
				if f.RetSet {
					b.WriteString("[]")
				}
			}
			b.WriteString(";\n      };\n")
		}
		b.WriteString("    };\n  };\n")
	}
	b.WriteString("}\n\n")
	// Shorthands: Tables<"todos">, and one alias per table.
	if len(schemas) > 0 {
		def := schemas[0]
		fmt.Fprintf(&b, "export type Tables<T extends keyof Database[%q][\"Tables\"]> = Database[%q][\"Tables\"][T][\"Row\"];\n", def, def)
		fmt.Fprintf(&b, "export type TablesInsert<T extends keyof Database[%q][\"Tables\"]> = Database[%q][\"Tables\"][T][\"Insert\"];\n", def, def)
		fmt.Fprintf(&b, "export type TablesUpdate<T extends keyof Database[%q][\"Tables\"]> = Database[%q][\"Tables\"][T][\"Update\"];\n", def, def)
		for _, t := range by[def] {
			kind := "Tables"
			if !writable(t) {
				kind = "Views"
			}
			fmt.Fprintf(&b, "export type %s = Database[%q][%q][%q][\"Row\"];\n", camel(t.Name, true), def, kind, t.Name)
		}
	}
	return b.String()
}

// ---- Dart -------------------------------------------------------------------

func dartScalar(typname string) string {
	switch typname {
	case "int2", "int4", "int8", "oid":
		return "int"
	case "float4", "float8", "numeric", "money":
		return "num"
	case "bool":
		return "bool"
	case "json", "jsonb":
		return "dynamic"
	case "timestamptz", "timestamp":
		return "DateTime"
	}
	return "String"
}

func dartType(c *datacat.Column) string {
	t := dartScalar(c.TypName)
	if c.Category == 'A' {
		t = "List<" + dartScalar(strings.TrimPrefix(c.TypName, "_")) + ">"
	}
	if c.Nullable && t != "dynamic" {
		t += "?"
	}
	return t
}

func dartFrom(c *datacat.Column, expr string) string {
	base := dartScalar(c.TypName)
	nullable := c.Nullable
	switch {
	case c.Category == 'A':
		elem := dartScalar(strings.TrimPrefix(c.TypName, "_"))
		conv := "(" + expr + " as List).map((e) => e as " + elem + ").toList()"
		if elem == "num" {
			conv = "(" + expr + " as List).map((e) => e as num).toList()"
		}
		if nullable {
			return expr + " == null ? null : " + conv
		}
		return conv
	case base == "DateTime":
		if nullable {
			return expr + " == null ? null : DateTime.parse(" + expr + " as String)"
		}
		return "DateTime.parse(" + expr + " as String)"
	case base == "dynamic":
		return expr
	}
	if nullable {
		return expr + " as " + base + "?"
	}
	return expr + " as " + base
}

func dartTo(c *datacat.Column, field string) string {
	if dartScalar(c.TypName) == "DateTime" && c.Category != 'A' {
		if c.Nullable {
			return field + "?.toIso8601String()"
		}
		return field + ".toIso8601String()"
	}
	return field
}

func genDart(cat *datacat.Catalog, o Options) string {
	var b strings.Builder
	b.WriteString(header("//", o.Ref))
	b.WriteString("// ignore_for_file: type=lint\n\n")
	schemas, by := relations(cat)
	for _, s := range schemas {
		for _, t := range by[s] {
			name := camel(t.Name, true)
			if s != cat.Schemas[0] {
				name = camel(s, true) + name
			}
			fmt.Fprintf(&b, "/// A row of %s.%s.\nclass %s {\n", t.Schema, t.Name, name)
			for _, c := range t.Columns {
				fmt.Fprintf(&b, "  final %s %s;\n", dartType(c), camel(c.Name, false))
			}
			fmt.Fprintf(&b, "\n  const %s({", name)
			for i, c := range t.Columns {
				if i > 0 {
					b.WriteString(", ")
				}
				if c.Nullable {
					fmt.Fprintf(&b, "this.%s", camel(c.Name, false))
				} else {
					fmt.Fprintf(&b, "required this.%s", camel(c.Name, false))
				}
			}
			b.WriteString("});\n\n")
			fmt.Fprintf(&b, "  static const table = %q;\n\n", t.Name)
			fmt.Fprintf(&b, "  factory %s.fromJson(Map<String, dynamic> json) => %s(\n", name, name)
			for _, c := range t.Columns {
				fmt.Fprintf(&b, "        %s: %s,\n", camel(c.Name, false), dartFrom(c, "json['"+c.Name+"']"))
			}
			b.WriteString("      );\n\n  Map<String, dynamic> toJson() => {\n")
			for _, c := range t.Columns {
				if c.Generated {
					continue
				}
				fmt.Fprintf(&b, "        '%s': %s,\n", c.Name, dartTo(c, camel(c.Name, false)))
			}
			b.WriteString("      };\n}\n\n")
		}
	}
	return b.String()
}

// ---- Go ---------------------------------------------------------------------

func goScalar(typname string) string {
	switch typname {
	case "int2":
		return "int16"
	case "int4":
		return "int32"
	case "int8", "oid":
		return "int64"
	case "float4":
		return "float32"
	case "float8":
		return "float64"
	case "numeric", "money":
		return "json.Number"
	case "bool":
		return "bool"
	case "json", "jsonb":
		return "json.RawMessage"
	case "timestamptz", "timestamp":
		return "time.Time"
	}
	return "string"
}

func goType(c *datacat.Column, ptr bool) string {
	t := goScalar(c.TypName)
	if c.Category == 'A' {
		return "[]" + goScalar(strings.TrimPrefix(c.TypName, "_"))
	}
	if t == "json.RawMessage" {
		return t
	}
	if ptr {
		return "*" + t
	}
	return t
}

func genGo(cat *datacat.Catalog, o Options) string {
	pkg := o.Package
	if pkg == "" {
		pkg = "pgdtypes"
	}
	var body strings.Builder
	usesTime, usesJSON := false, false
	note := func(t string) {
		if strings.Contains(t, "time.") {
			usesTime = true
		}
		if strings.Contains(t, "json.") {
			usesJSON = true
		}
	}
	schemas, by := relations(cat)
	for _, s := range schemas {
		for _, t := range by[s] {
			name := goName(t.Name)
			if s != cat.Schemas[0] {
				name = goName(s) + name
			}
			fmt.Fprintf(&body, "// %s is a row of %s.%s.\ntype %s struct {\n", name, t.Schema, t.Name, name)
			for _, c := range t.Columns {
				gt := goType(c, c.Nullable)
				note(gt)
				fmt.Fprintf(&body, "\t%s %s `json:%q`\n", goName(c.Name), gt, c.Name)
			}
			body.WriteString("}\n\n")
			fmt.Fprintf(&body, "// %sTable is the name to use in data API paths.\nconst %sTable = %q\n\n", name, name, tableRef(cat, t))
			if !writable(t) {
				continue
			}
			fmt.Fprintf(&body, "// %sInsert is a new row: nil fields take the column's default or null.\ntype %sInsert struct {\n", name, name)
			for _, c := range t.Columns {
				if c.Generated {
					continue
				}
				gt := goType(c, optional(c))
				note(gt)
				tag := c.Name
				if optional(c) {
					tag += ",omitempty"
				}
				fmt.Fprintf(&body, "\t%s %s `json:%q`\n", goName(c.Name), gt, tag)
			}
			body.WriteString("}\n\n")
			fmt.Fprintf(&body, "// %sUpdate changes the non-nil fields.\ntype %sUpdate struct {\n", name, name)
			for _, c := range t.Columns {
				if c.Generated {
					continue
				}
				gt := goType(c, true)
				note(gt)
				fmt.Fprintf(&body, "\t%s %s `json:\"%s,omitempty\"`\n", goName(c.Name), gt, c.Name)
			}
			body.WriteString("}\n\n")
		}
	}
	var b strings.Builder
	b.WriteString(header("//", o.Ref))
	fmt.Fprintf(&b, "\n// Package %s holds the project's table types.\npackage %s\n\n", pkg, pkg)
	switch {
	case usesTime && usesJSON:
		b.WriteString("import (\n\t\"encoding/json\"\n\t\"time\"\n)\n\n")
	case usesTime:
		b.WriteString("import \"time\"\n\n")
	case usesJSON:
		b.WriteString("import \"encoding/json\"\n\n")
	}
	b.WriteString(body.String())
	return b.String()
}

func tableRef(cat *datacat.Catalog, t *datacat.Table) string {
	if t.Schema == cat.Schemas[0] {
		return t.Name
	}
	return t.Schema + "." + t.Name
}
