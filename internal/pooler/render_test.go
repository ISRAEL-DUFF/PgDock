const verifier = "SCRAM-SHA-256$4096:c2FsdA==$c3RvcmVk:c2VydmVy"

func TestRender(t *testing.T) {
	db, ul, err := Render(Config{
		Routes: []Route{
			{Database: "todo_8xq1", Host: "10.0.0.5", Port: 5432, PoolSize: 5, MaxDBConnections: 20},
			{Database: "blog_k2f9", Host: "shared-pg", Port: 5432},
		},
		Users: []User{
			{Name: "todo_8xq1_owner", Secret: verifier},
			{Name: "blog_k2f9_owner", Secret: verifier},
		},
	})
	if err != nil {
		t.Fatal(err)
	}
	want := "; Generated by pgdock-server. Do not edit: changes are overwritten.\n[databases]\n" +
		"blog_k2f9 = host=shared-pg port=5432 dbname=blog_k2f9\n" +
		"todo_8xq1 = host=10.0.0.5 port=5432 dbname=todo_8xq1 pool_size=5 max_db_connections=20\n"
	if string(db) != want {
		t.Fatalf("databases.ini:\n%s\nwant:\n%s", db, want)
	}
	wantUL := `"blog_k2f9_owner" "` + verifier + "\"\n" + `"todo_8xq1_owner" "` + verifier + "\"\n"
	if string(ul) != wantUL {
		t.Fatalf("userlist:\n%s\nwant:\n%s", ul, wantUL)
	}
}

func TestRenderRejectsInjection(t *testing.T) {
	bad := []Config{
		{Routes: []Route{{Database: "x\n[pgbouncer]", Host: "h", Port: 1}}},
		{Routes: []Route{{Database: "x", Host: "h auth_user=postgres", Port: 1}}},
		{Routes: []Route{{Database: "x", Host: "h", Port: 0}}},
		{Routes: []Route{{Database: "x", Host: "h", Port: 1}, {Database: "x", Host: "h", Port: 1}}},
		{Users: []User{{Name: "u\"", Secret: verifier}}},
		{Users: []User{{Name: "u", Secret: "plaintext"}}},
		{Users: []User{{Name: "u", Secret: verifier + "\"\n\"admin\" \"x"}}},
	}
	for i, c := range bad {
		if _, _, err := Render(c); err == nil {
			t.Errorf("case %d accepted", i)
		}
	}
}

func TestWriteFileAtomic(t *testing.T) {
	dir := t.TempDir()
	p := filepath.Join(dir, "f")
	changed, err := WriteFileAtomic(p, []byte("a"), 0o640)
	if err != nil || !changed {
		t.Fatalf("first write: %v %v", changed, err)
	}
	if changed, _ := WriteFileAtomic(p, []byte("a"), 0o640); changed {
		t.Fatal("identical write reported a change")
	}
	if changed, _ := WriteFileAtomic(p, []byte("b"), 0o640); !changed {
		t.Fatal("new content not reported")
	}
	b, _ := os.ReadFile(p)
	entries, _ := os.ReadDir(dir)
	if string(b) != "b" || len(entries) != 1 || strings.HasPrefix(entries[0].Name(), ".") {
		t.Fatalf("unexpected state: %q %v", b, entries)
	}
}
