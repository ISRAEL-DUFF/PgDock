#!/bin/sh
# Install PGDock on this host with Docker Compose (spec §11.1).
#
#   cd deploy/compose && ./install.sh
#
# Generates .env with fresh secrets (kept if it already exists), starts the
# stack, and prints the one-time setup code for the web UI.
set -eu
cd "$(dirname "$0")"

command -v docker >/dev/null || { echo "Docker is required: https://docs.docker.com/engine/install/" >&2; exit 1; }
docker compose version >/dev/null 2>&1 || { echo "Docker Compose v2 is required." >&2; exit 1; }

rand() { head -c "$1" /dev/urandom | base64 | tr -d '\n'; }
rand_url() { rand "$1" | tr '+/' '-_' | tr -d '='; }

if [ ! -f .env ]; then
	printf 'Web UI hostname (e.g. pgdock.example.com): '
	read -r ui_domain
	printf 'Email for Let'"'"'s Encrypt notices: '
	read -r email
	public_ip=$(curl -fsS --max-time 5 https://api.ipify.org 2>/dev/null || true)
	umask 077
	cat > .env <<ENV
# Generated by install.sh. Back this file up: PGDOCK_MASTER_KEY decrypts
# every secret PGDock stores, and losing it loses them.
PGDOCK_UI_DOMAIN=${ui_domain}
PGDOCK_ACME_EMAIL=${email}
PGDOCK_PUBLIC_IPS=${public_ip}
PGDOCK_MASTER_KEY=$(rand 32)
METADATA_DB_PASSWORD=$(rand_url 24)
SHARED_ADMIN_PASSWORD=$(rand_url 24)
POOLER_ADMIN_PASSWORD=$(rand_url 24)
ENV
	echo "Wrote .env (mode 600)."
fi
# Added in M3; older .env files lack it.
grep -q '^AGENT_BOOTSTRAP_TOKEN=' .env || echo "AGENT_BOOTSTRAP_TOKEN=$(rand_url 32)" >> .env

# Dedicated instances run this image (PostgreSQL 18 + WAL-G).
docker build -t pgdock-postgres:18-walg3.0.9 ../images/postgres
docker compose up -d --build --wait

echo
echo "PGDock is running. Open https://$(grep '^PGDOCK_UI_DOMAIN=' .env | cut -d= -f2-) and enter this setup code:"
docker compose logs pgdock-server 2>/dev/null | grep -o '"setup_code":"[^"]*"' | tail -1 | cut -d'"' -f4
